    day_tag = parse_date_to_day_tag(date)
    files = sorted(path for path in glob.glob(UNATTENDED_GLOB) if os.path.isfile(path))

    if day_tag:
        files = [path for path in files if extract_day_tag(path) == day_tag]

    frames = []
