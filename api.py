@app.get("/api/people")
def get_people_logs(
    camera: Optional[str] = Query(default=None, description="Camera label, ex: Front_left"),
    date: Optional[str] = Query(default=None, description="YYYY-MM-DD or YYYYMMDD"),
    person_id: Optional[str] = Query(default=None, description="Person ID, ex: 015"),
    limit: int = Query(default=2000, ge=1, le=50000),
) -> List[Dict[str, Any]]:
    day_tag = parse_date_to_day_tag(date)
    files = filter_files(PEOPLE_GLOB, camera, day_tag)

    frames = []
    for file_path in files:
        df = read_csv_safe(file_path)
        if df.empty:
            continue

        cam_label = os.path.basename(os.path.dirname(file_path))
        df["cam_name"] = cam_label

        if person_id is not None and "person_id" in df.columns:
            df = df[df["person_id"].astype(str) == str(person_id)]

        frames.append(df)

    if not frames:
        return []

    merged = pd.concat(frames, ignore_index=True)
    merged = apply_time_sort_and_limit(merged, limit)
    return records_from_df(merged)


